from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from database import get_db
from models import Book
from schemas import BookIn, ErrorResponse
from auth import require_api_key

router = APIRouter(
    prefix="/books",
    tags=["books"]
)


@router.get("")                                          
def get_all_books(db: Session = Depends(get_db)):           #Opens a DB session and closes when it's done
    """Returns a list of all books in the database."""
    return db.query(Book).all()                             #Ask SQL Alchemy for all rows in the book table and return 

@router.get(
    "/{book_id}",
    responses={404: {"model": ErrorResponse, "description": "Book not found"}}
    )
def get_book(book_id: int, db: Session = Depends(get_db)):              #Takes the ID from the URL and get a DB session 
    book = db.query(Book).filter(Book.id == book_id).first()            #Searches the DB for first ID matching book 
    if book is None:                                                    
        raise HTTPException(status_code=404, detail="Book not found")   #If Book isnt found, raise a 404 error 
    return book                                                         #Return the Book

@router.post(
    "", 
    status_code=201, 
    dependencies=[Depends(require_api_key)],   #Now Require the API Key for the Post Function
    responses={401: {"model": ErrorResponse, "description": "Missing or invalid API Key"}}
)
def create_book(book: BookIn, db: Session = Depends(get_db)):           #Create Book command, validate data with BookIn, get DB session 
    new_book = Book(title=book.title, author=book.author)               #Create new SQLAlchemy book object
    db.add(new_book)                                                    #Add book to database 
    db.commit()                                                         #Save it to Postgres 
    db.refresh(new_book)                                                #Update the autogenerated ID to the python object                  
    return new_book                                                     #Return the new book

@router.put(
    "/{book_id}", 
    dependencies=[Depends(require_api_key)],
    responses = {
        401: {"model": ErrorResponse, "description": "Missing/Invalid API Key"},
        404: {"model": ErrorResponse, "description:": "Book not Found"}
    }
    )                   #Now Require the API Key for the Put Function
def update_book(book_id: int, updated_book: BookIn, db: Session = Depends(get_db)):     #Get ID, new data, and DB session                               
    book = db.query(Book).filter(Book.id == book_id).first()                            #Find the book to match the URL ID 
    if book is None:
        raise HTTPException(status_code=404, detail="Book not found")                   #If the Book isn't found, return a 404 error 
    book.title = updated_book.title                                                     
    book.author = updated_book.author                                                   
    db.commit()                                                                         #Save changes to Postgres 
    db.refresh(book)                                                                    #Update the autogenerated ID to the python object
    return book                                                                         #Return the Updated Book

@router.delete(
    "/{book_id}", 
    dependencies=[Depends(require_api_key)],    #Now Require the API Key for the Delete Function
    responses={
        401: {"model": ErrorResponse, "description": "Missing or invalid API key"},
        404: {"model": ErrorResponse, "description": "Book not found"}
    }
)
def delete_book(book_id: int, db: Session = Depends(get_db)):           #Get the ID and the DB session
    book = db.query(Book).filter(Book.id == book_id).first()            #Find the matching book 
    if book is None:    
        raise HTTPException(status_code=404, detail="Book not found")   #If the Book isn't found, return a 404 error 
    db.delete(book)                                                     #Delete the Book 
    db.commit()                                                         #Save Changes to Postgres 
    return book                                                         #Return the Deleted Book